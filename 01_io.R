# ----------------------------------------------------------------------------
# А.3. Чтение внешнего текстового файла: read.table()
# ----------------------------------------------------------------------------
# Файл data/example.txt имеет вид:
#   name age
#   John 25
#   Mary 28
#   Jim 19
# Разделитель — пробел (это значение по умолчанию для read.table),
# первая строка — заголовок, поэтому header = TRUE.

v3 <- read.table("data/example.txt", header = TRUE)

cat("\n--- А.3. read.table('example.txt') ---\n")
print(v3)
cat("Класс объекта:", class(v3), "\n")
cat("Размерность:", dim(v3), "(строк, столбцов)\n")
str(v3)

# Обратите внимание: столбец age прочитан как integer, а name — как character.
# read.table сама определяет тип каждого столбца (type.convert).
# В R версии 4.0 и выше строки НЕ превращаются в факторы автоматически;
# до 4.0 поведение было обратным (stringsAsFactors = TRUE по умолчанию).
# Если преподаватель работает на старой версии, результат str() будет иным.


# ----------------------------------------------------------------------------
# А.4. Чтение данных сразу в матрицу
# ----------------------------------------------------------------------------
# scan() без указания what читает числа. Файл matrix.txt содержит
# 6 строк по 3 значения, разделённых пробелом, то есть 18 чисел подряд.
# scan() вернёт ПЛОСКИЙ вектор из 18 элементов, и задача matrix() —
# свернуть его в таблицу.
#   nrow  = 6      — сколько строк должно получиться
#   byrow = TRUE   — заполнять матрицу ПО СТРОКАМ.
#                    Это критично: по умолчанию R заполняет по столбцам,
#                    и матрица получится транспонированной относительно файла.

raw_values <- scan("data/matrix.txt", quiet = TRUE)

cat("\n--- А.4. scan('matrix.txt') ---\n")
cat("Прочитано значений:", length(raw_values), "\n")
print(raw_values)

my_matrix <- matrix(raw_values, nrow = 6, byrow = TRUE)

cat("\nМатрица 6x3:\n")
print(my_matrix)
cat("Размерность:", dim(my_matrix), "\n")

# Самопроверка: количество прочитанных чисел должно делиться на nrow.
stopifnot(length(raw_values) == 18, identical(dim(my_matrix), c(6L, 3L)))

