# ----------------------------------------------------------------------------
# Б.1. Обоснование выбора библиотеки (этот абзац идёт в отчёт)
# ----------------------------------------------------------------------------
# Рассмотрены три варианта:
#   xlsx    — требует установленной Java и пакета rJava. Отвергнут:
#             лишняя внешняя зависимость, частые проблемы с разрядностью JDK.
#   writexl — только ЗАПИСЬ, зато без зависимостей и очень быстрый.
#   openxlsx— и запись, и чтение, поддержка форматирования, стилей,
#             нескольких листов, без Java.
#   readxl  — только ЧТЕНИЕ, но самое надёжное и быстрое, входит в tidyverse.
#
# Выбор: записываем через openxlsx (нужно управление листами),
# читаем через readxl (штатный инструмент для чтения).

# ----------------------------------------------------------------------------
# Б.2. Готовим три таблицы складской тематики
# ----------------------------------------------------------------------------
receiving <- data.frame(
  doc_no   = c("ПР-001", "ПР-002", "ПР-003"),
  supplier = c("ООО Вектор", "ИП Смирнов", "ООО Вектор"),
  sku_qty  = c(120, 45, 310),
  date     = as.Date(c("2026-09-01", "2026-09-03", "2026-09-05"))
)

picking <- data.frame(
  order_no = c("ЗК-1001", "ЗК-1002", "ЗК-1003", "ЗК-1004"),
  picker   = c("Иванов", "Петров", "Иванов", "Сидоров"),
  lines    = c(12, 7, 21, 5),
  minutes  = c(18, 9, 27, 6)
)

stock <- data.frame(
  cell    = c("A-01-01", "A-01-02", "B-02-01", "B-02-02", "C-03-01"),
  sku     = c("SKU-100", "SKU-101", "SKU-100", "SKU-102", "SKU-103"),
  qty     = c(40, 15, 60, 0, 25)
)

# ----------------------------------------------------------------------------
# Б.3. Записываем их на РАЗНЫЕ вкладки одного xlsx
# ----------------------------------------------------------------------------
# Вариант 1 — через объект Workbook (полный контроль над листами).
wb <- createWorkbook()

addWorksheet(wb, "Priemka")
addWorksheet(wb, "Otbor")
addWorksheet(wb, "Ostatki")

writeData(wb, sheet = "Priemka", x = receiving)
writeData(wb, sheet = "Otbor",   x = picking)
writeData(wb, sheet = "Ostatki", x = stock)

xlsx_path <- "output/lab1_sheets.xlsx"
saveWorkbook(wb, xlsx_path, overwrite = TRUE)

cat("\n--- Б.3. Создан файл:", xlsx_path, "---\n")

# Имена вкладок заданы латиницей осознанно: кириллица в названиях листов
# допустима, но при чтении на другой локали (особенно Windows CP1251)
# регулярно превращается в "кракозябры". Для сдаваемой работы это риск.

# Вариант 2 — то же самое одной строкой через именованный список.
# openxlsx::write.xlsx(
#   list(Priemka = receiving, Otbor = picking, Ostatki = stock),
#   file = "output/lab1_sheets_alt.xlsx"
# )

# ----------------------------------------------------------------------------
# Б.4. Читаем вкладки обратно В ПЕРЕМЕННЫЕ
# ----------------------------------------------------------------------------
sheet_names <- excel_sheets(xlsx_path)

cat("\n--- Б.4. Вкладки в файле ---\n")
print(sheet_names)

# Способ 1 — каждая вкладка в отдельную переменную.
# assign() создаёт переменную, имя которой вычисляется во время выполнения.
# Это тот же механизм, который понадобится в задании 7 с пятью X.
for (s in sheet_names) {
  assign(
    x     = paste0("xl_", s),
    value = as.data.frame(read_excel(xlsx_path, sheet = s))
  )
}

cat("\nСозданные переменные:\n")
print(ls(pattern = "^xl_"))

cat("\nСодержимое xl_Otbor:\n")
print(xl_Otbor)

# Способ 2 — все вкладки в один именованный список.
# Предпочтительнее: не засоряет глобальное окружение и легко обходится в цикле.
xl_list <- lapply(sheet_names, function(s) {
  as.data.frame(read_excel(xlsx_path, sheet = s))
})
names(xl_list) <- sheet_names

cat("\nСписок из", length(xl_list), "элементов:",
    paste(names(xl_list), collapse = ", "), "\n")
cat("Число строк на каждой вкладке:\n")
print(sapply(xl_list, nrow))

# Проверка корректности: то, что записали, должно совпасть с тем, что прочитали.
cat("\nПроверка совпадения числа строк при записи и чтении:\n")
print(c(
  Priemka = nrow(receiving) == nrow(xl_list$Priemka),
  Otbor   = nrow(picking)   == nrow(xl_list$Otbor),
  Ostatki = nrow(stock)     == nrow(xl_list$Ostatki)
))

# Известный нюанс: read_excel возвращает tibble, а не data.frame,
# и столбец date может прийти как POSIXct вместо Date.
# Поэтому обёртка as.data.frame() и отдельная проверка типов:
cat("\nТип столбца date после обратного чтения:",
    class(xl_list$Priemka$date), "\n")


# ============================================================================
# ЧАСТЬ В. ЗАДАНИЕ 2
# Обратная операция: из переменной (матрицы) выгрузить данные в Excel.
# ============================================================================

# Берём матрицу my_matrix, полученную в пункте А.4 из matrix.txt.
# Подписываем строки и столбцы, чтобы выгрузка была читаемой:
# трактуем её как матрицу занятости ячеек склада.
export_matrix <- my_matrix
rownames(export_matrix) <- paste0("Ряд-", seq_len(nrow(export_matrix)))
colnames(export_matrix) <- paste0("Ярус-", seq_len(ncol(export_matrix)))

cat("\n--- В. Матрица к выгрузке ---\n")
print(export_matrix)

# openxlsx умеет писать матрицу напрямую, но имена строк по умолчанию
# теряются — их нужно запросить явно через rowNames = TRUE.
wb2 <- createWorkbook()
addWorksheet(wb2, "Matrix")
writeData(wb2, sheet = "Matrix", x = export_matrix, rowNames = TRUE)
saveWorkbook(wb2, "output/matrix_export.xlsx", overwrite = TRUE)

cat("Создан файл: output/matrix_export.xlsx\n")

# Альтернатива через writexl: он НЕ принимает матрицу и НЕ пишет имена строк,
# поэтому матрицу нужно предварительно превратить в data.frame,
# а имена строк — в обычный столбец. Это наглядно показывает разницу библиотек.
export_df <- data.frame(
  row_name = rownames(export_matrix),
  as.data.frame(export_matrix),
  row.names = NULL
)
write_xlsx(export_df, "output/matrix_export_writexl.xlsx")

cat("Создан файл: output/matrix_export_writexl.xlsx\n")

# Контроль: читаем выгруженный файл обратно и сравниваем с исходной матрицей.
check_back <- as.data.frame(read_excel("output/matrix_export.xlsx"))
cat("\nПрочитано обратно, размерность:", dim(check_back), "\n")
print(check_back)

# Первый столбец при обратном чтении — это бывшие имена строк,
# поэтому значений-столбцов на один меньше, чем столбцов в файле.
values_back <- as.matrix(check_back[, -1])
dimnames(values_back) <- NULL
dimnames(export_matrix) <- NULL

cat("\nСовпадают ли значения матрицы до выгрузки и после чтения:",
    identical(values_back, export_matrix), "\n")

# Если identical() вернёт FALSE, вероятная причина — тип данных:
# Excel хранит числа как double, а scan() мог дать integer.
# Тогда корректной проверкой будет all.equal():
cat("Проверка all.equal():",
    isTRUE(all.equal(values_back, export_matrix)), "\n")
