# ----------------------------------------------------------------------------
# scan("", sep = ',', what = "") читает данные ИЗ КОНСОЛИ (первый аргумент —
# пустая строка, то есть файл не указан).
#   sep  = ','  — разделитель значений
#   what = ""   — тип ожидаемых данных: пустая строка означает character.
#                 Если написать what = numeric(), R будет ждать числа
#                 и упадёт на любом нечисловом вводе.
# Ввод завершается ПУСТОЙ СТРОКОЙ (нажать Enter на пустой строке).
#
# ВАЖНО: эта команда работает только в интерактивной консоли.
# При запуске через Rscript или Knit она зависнет или вернёт пустой вектор.
# Поэтому здесь она закомментирована, а в отчёт идёт скриншот из консоли.

