# А.6. Оператор глобального присваивания <<-
# ----------------------------------------------------------------------------
make_global <- function(u) {
  u <<- 2 * u   # ищет u ВЫШЕ своего окружения, не находит — создаёт глобальную
  z <- 2 * z    # обычное присваивание — создаёт ЛОКАЛЬНУЮ z, глобальная не меняется
}

x <- 1
z <- 3
if (exists("u", envir = globalenv(), inherits = FALSE)) rm(u)

cat("\n--- А.6. Оператор <<- ---\n")
# В методичке здесь стоит просто u — при запуске скрипта целиком R
# остановится с ошибкой «объект 'u' не найден». Проверяем безопасно:
cat("u существует ДО вызова:   ", exists("u", envir = globalenv(), inherits = FALSE), "\n")
make_global(x)
cat("u существует ПОСЛЕ вызова:", exists("u", envir = globalenv(), inherits = FALSE), "\n")
cat("x =", x, "(не изменился)\n")
cat("z =", z, "(не изменился: внутри функции была своя, локальная z)\n")
cat("u =", u, "(создана в глобальном окружении: 2 * 1)\n")


