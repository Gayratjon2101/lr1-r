# Напишите функцию, которая:
#  1) создаст 5 txt-файлов с числовыми значениями
#  2) прочитает каждый в переменную по имени X — именно 5 переменных
#     с ОДИНАКОВЫМ именем (подсказка: окружения)
#  3) в цикле по этим 5 переменным построит ОДИН график
#  4) объединит 5 строк в дата-фрейм и выведет его в консоль
#
# Ключевая идея: в одном окружении может быть только одна переменная X.
# Значит, нужно 5 окружений — по одной X в каждом. Это тот же механизм,
# что в замыканиях (А.8): разные окружения хранят переменные с одним именем
# независимо друг от друга.

# Значения по умолчанию совпадают с файлами 1.txt–5.txt из методички
default_values <- list(c(1, 2, 3), c(2, 3, 4), c(4, 5, 6), c(6, 7, 7), c(8, 9, 0))

task7 <- function(dir = "output/task7", values = default_values,
                  plot_file = "output/task7_plot.png") {

  # Шаг 1. Создаём 5 файлов
  dir.create(dir, recursive = TRUE, showWarnings = FALSE)
  paths <- file.path(dir, paste0(seq_along(values), ".txt"))
  for (i in seq_along(values)) {
    writeLines(paste(values[[i]], collapse = ","), paths[i])
  }
  cat("Шаг 1. Создано файлов:", length(paths), "\n")

  # Шаг 2. Каждый файл — в переменную X в СВОЁМ окружении
  envs <- list()
  for (i in seq_along(paths)) {
    e <- new.env()
    assign("X", scan(paths[i], sep = ",", quiet = TRUE), envir = e)
    envs[[i]] <- e
  }
  names(envs) <- basename(paths)

  cat("Шаг 2. Пять переменных X в пяти окружениях:\n")
  for (nm in names(envs)) {
    cat("  ", nm, " -> ", format(envs[[nm]]), " X = ",
        paste(get("X", envir = envs[[nm]]), collapse = ", "), "\n", sep = "")
  }

  # Шаг 3. Один график в цикле по пяти X
  all_vals <- unlist(lapply(envs, function(e) get("X", envir = e)))
  max_len  <- max(sapply(envs, function(e) length(get("X", envir = e))))

  draw <- function() {
    plot(NA, xlim = c(1, max_len), ylim = c(min(all_vals), max(all_vals) + 3),
         xaxt = "n", xlab = "Позиция значения в файле", ylab = "Значение",
         main = "Значения X из пяти окружений")
    axis(1, at = seq_len(max_len))
    for (i in seq_along(envs)) {
      vals <- get("X", envir = envs[[i]])
      lines(seq_along(vals), vals, type = "b", col = i, pch = i, lwd = 2)
    }
    legend("top", legend = names(envs), col = seq_along(envs),
           pch = seq_along(envs), lwd = 2, horiz = TRUE, bty = "n", cex = 0.85)
  }

  png(plot_file, width = 900, height = 600)  # сохраняем в файл для отчёта
  draw()
  dev.off()
  draw()                                     # и показываем на панели Plots
  cat("Шаг 3. График построен и сохранён:", plot_file, "\n")

  # Шаг 4. Объединяем 5 строк в дата-фрейм.
  # Если в файлах разное число значений, короткие строки дополняются NA,
  # иначе rbind() молча «зациклил» бы короткие векторы.
  rows <- lapply(envs, function(e) get("X", envir = e))
  L    <- max(lengths(rows))
  rows <- lapply(rows, function(v) c(v, rep(NA, L - length(v))))

  df <- as.data.frame(do.call(rbind, rows))
  names(df) <- paste0("value_", seq_len(L))
  df <- cbind(file = names(envs), df, row.names = NULL)

  cat("Шаг 4. Дата-фрейм:\n")
  print(df)

  invisible(list(envs = envs, df = df))
}

