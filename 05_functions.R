# ----------------------------------------------------------------------------
# А.5. Отдельное окружение и компиляция функции
# ----------------------------------------------------------------------------
e1 <- new.env(parent = baseenv())
assign("x1", 1:1000, envir = e1)
assign("y1", 1:1000, envir = e1)
assign("test_cmp",
       compiler::cmpfun(function(x1, y1) {
         z <- x1^2 + y1^2
         Reduce("+", z)
       }),
       envir = e1)

cat("\n--- А.5. Окружение e1 ---\n")
cat("Результат test_cmp:",
    do.call("test_cmp", list(as.name("x1"), as.name("y1")), envir = e1), "\n")
cat("Объекты в e1:", paste(ls(e1), collapse = ", "), "\n")
cat("Есть ли x1 в глобальном окружении:",
    exists("x1", envir = globalenv(), inherits = FALSE), "\n")

# Сравнение скорости. На 1000 элементах, как в методичке, время равно нулю
# и сравнивать нечего, поэтому берём миллион.
# Уточнение к методичке: начиная с R 3.4 работает JIT-компилятор, который
# сам компилирует функции при первом вызове. Поэтому cmpfun() почти
# не даёт выигрыша. Реальный выигрыш дают векторные функции вроде sum().
n  <- 1e6
xb <- as.numeric(1:n)
yb <- as.numeric(1:n)

compiled <- compiler::cmpfun(function(x1, y1) Reduce("+", x1^2 + y1^2))
plain    <- function(x1, y1) Reduce("+", x1^2 + y1^2)
vector_v <- function(x1, y1) sum(x1^2 + y1^2)

t_cmp   <- system.time(r1 <- compiled(xb, yb))["elapsed"]
t_plain <- system.time(r2 <- plain(xb, yb))["elapsed"]
t_vec   <- system.time(r3 <- vector_v(xb, yb))["elapsed"]

cat("\nВремя на", format(n, big.mark = " "), "элементов, секунд:\n")
print(data.frame(
  variant = c("cmpfun + Reduce", "обычная + Reduce", "sum()"),
  seconds = c(t_cmp, t_plain, t_vec),
  same_result = c(isTRUE(all.equal(r1, r3)), isTRUE(all.equal(r2, r3)), TRUE),
  row.names = NULL
))


