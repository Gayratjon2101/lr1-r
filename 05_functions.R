# Напишите функцию, которая:
#  1) прочитает .txt-файл со строкой «Лабораторная работа №3», через read.table()
#  2) прочитает текст из консоли
#  3) сохранит эти данные в дата-фрейм
#  4) выведет его на печать командой print()
#  5-6) коммит и пуш — выполняются в RStudio после запуска скрипта
#
# Два уточнения к формулировке задания:
#  - «команда input()» в R не существует (это функция Python).
#    В R ввод с консоли — readline().
#  - текст «Лабораторная работа №3» оставлен как в задании: это нумерация
#    из исходного документа, где этот блок был третьей работой.

task6 <- function(path = "output/task6_note.txt", console_text = NULL) {

  # Шаг 1а. Создаём файл. Кодировку указываем явно, чтобы кириллица
  # и знак № одинаково читались на любой системе.
  con <- file(path, encoding = "UTF-8")
  writeLines("Лабораторная работа №3", con)
  close(con)

  # Шаг 1б. Читаем через read.table().
  # Подвох: по умолчанию read.table() делит строку по ПРОБЕЛАМ,
  # и одна фраза превращается в три столбца. Чтобы строка читалась
  # целиком, задаём разделитель-табуляцию, которой в тексте нет.
  # quote = "" — не считать кавычки особыми символами.
  from_file <- read.table(path, sep = "\t", quote = "", header = FALSE,
                          col.names = "text", fileEncoding = "UTF-8")

  # Шаг 2. Ввод с консоли.
  # Если текст не передан аргументом — спрашиваем у пользователя.
  # interactive() проверяет, есть ли живая консоль: при запуске без неё
  # readline() вернул бы пустую строку, поэтому подставляем значение.
  if (is.null(console_text)) {
    if (interactive()) {
      console_text <- readline("Введите любой текст и нажмите Enter: ")
    } else {
      console_text <- "(запуск без консоли, ввод недоступен)"
    }
  }

  # Шаг 3. Сохраняем в дата-фрейм
  result <- data.frame(
    source = c("файл", "консоль"),
    text   = c(from_file$text[1], console_text)
  )

  # Шаг 4. Печать
  print(result)
  invisible(result)
}

cat("\n--- Б. ЗАДАНИЕ 6 ---\n")

# Для отчёта: что дал бы read.table() с настройками по умолчанию
cat("read.table() по умолчанию разбивает фразу по пробелам:\n")
