# А.3. Замена тела функции
# ----------------------------------------------------------------------------
g <- function(h, a, b) h(a, b)
body(g) <- quote(2 * x + 3)
x <- 3

cat("\n--- А.3. Новое тело функции ---\n")
print(g)
cat("g(3) =", g(3), "\n")
# Важно для защиты: x НЕ является аргументом g. Аргумент 3 попадает в h
# и не используется, а x берётся из глобального окружения, где x <- 3.
