library(stringr)


# ============================================================================
# 1. ВЕКТОРЫ
# ============================================================================
# Вектор — базовая структура R. Главное свойство: ОДНОРОДНОСТЬ,
# все элементы одного типа. Если смешать типы, R приведёт их к общему
# (character сильнее numeric, numeric сильнее logical).

sku      <- c("SKU-100", "SKU-101", "SKU-102", "SKU-103", "SKU-104")
qty      <- c(40, 15, 0, 25, 7)          # остаток в ячейке, шт.
weight   <- c(1.2, 0.8, 2.5, 0.35, 4.0)  # вес единицы, кг

cat("--- 1. Векторы ---\n")
print(sku)
print(qty)
cat("Типы:", class(sku), "/", class(qty), "\n")
cat("Длина вектора sku:", length(sku), "\n")

# Демонстрация принудительного приведения типов:
mixed <- c(1, 2, "три")
cat("Вектор c(1, 2, 'три') имеет тип:", class(mixed), "\n")
print(mixed)

# Векторы-последовательности (аналог x2 <- 1:5 из методички)
positions <- 1:5
tiers     <- 6:10

# Логическая индексация — ключевой приём R.
# Выражение qty > 0 даёт ЛОГИЧЕСКИЙ вектор, который затем используется
# как маска: остаются только те элементы, где TRUE.
cat("\nМаска qty > 0:\n")
print(qty > 0)
cat("Непустые ячейки:\n")
print(qty[qty > 0])
cat("Артикулы в непустых ячейках:\n")
print(sku[qty > 0])

# Векторные операции выполняются поэлементно, без цикла:
total_weight <- qty * weight
names(total_weight) <- sku
cat("\nОбщий вес по артикулам, кг:\n")
print(total_weight)


# ============================================================================
# 2. МАТРИЦЫ
# ============================================================================
# Матрица — вектор с атрибутом dim. Тоже однородна по типу.
# Смысл данных: остатки трёх артикулов в четырёх зонах склада.

stock_matrix <- matrix(
  c(40, 15,  0, 25,
     8, 12, 30,  5,
     0,  0, 18, 44),
  nrow  = 3,
  byrow = TRUE
)
rownames(stock_matrix) <- c("SKU-100", "SKU-101", "SKU-102")
colnames(stock_matrix) <- c("Зона A", "Зона B", "Зона C", "Зона D")

cat("\n--- 2. Матрица остатков ---\n")
print(stock_matrix)
cat("Размерность:", dim(stock_matrix), "\n")

# Индексация [строка, столбец]
cat("Остаток SKU-101 в зоне C:", stock_matrix["SKU-101", "Зона C"], "\n")
cat("Он же по номерам [2, 3]:",  stock_matrix[2, 3], "\n")

# Агрегация по измерениям
cat("\nИтого по артикулам (по строкам):\n")
print(rowSums(stock_matrix))
cat("Итого по зонам (по столбцам):\n")
print(colSums(stock_matrix))

# Подводный камень: при выборке одной строки R по умолчанию "роняет"
# размерность и возвращает вектор, а не матрицу.
cat("\nstock_matrix[1, ] — класс:", class(stock_matrix[1, ]), "\n")
cat("stock_matrix[1, , drop = FALSE] — класс:",
    class(stock_matrix[1, , drop = FALSE]), "\n")


# ============================================================================
# 3. ДАТА-ФРЕЙМЫ
# ============================================================================
# Дата-фрейм — список векторов ОДИНАКОВОЙ ДЛИНЫ, но РАЗНЫХ типов.
# Это главное отличие от матрицы и основной рабочий объект в анализе данных.

orders <- data.frame(
  order_no  = c("ЗК-1001", "ЗК-1002", "ЗК-1003", "ЗК-1004", "ЗК-1005"),
  picker    = c("Иванов", "Петров", "Иванов", "Сидоров", "Петров"),
  lines     = c(12, 7, 21, 5, 14),
  minutes   = c(18, 9, 27, 6, 20),
  urgent    = c(TRUE, FALSE, TRUE, FALSE, FALSE),
  stringsAsFactors = FALSE
)

cat("\n--- 3. Дата-фрейм заказов ---\n")
print(orders)
str(orders)

# Три способа обратиться к одному и тому же значению:
cat("\norders[3, 'minutes'] =", orders[3, "minutes"], "\n")
cat("orders$minutes[3]     =", orders$minutes[3], "\n")
cat("orders[[4]][3]        =", orders[[4]][3], "\n")

# Вычисляемый столбец: производительность отбора, строк в час
orders$lines_per_hour <- round(orders$lines / orders$minutes * 60, 1)

cat("\nС добавленным столбцом производительности:\n")
print(orders)

# Фильтрация строк логической маской
cat("\nСрочные заказы:\n")
print(orders[orders$urgent, c("order_no", "picker", "lines_per_hour")])

# Второй вариант сборки из методички — из готовых векторов
df2 <- data.frame(sku, qty, weight)
cat("\nДата-фрейм из трёх векторов:\n")
print(df2)

# Третий вариант — через rbind. Здесь важный нюанс:
# rbind() склеивает векторы в МАТРИЦУ, а матрица однородна,
# поэтому числа превращаются в строки. Дата-фрейм получается
# из символов, а не из чисел — на защите это любят спрашивать.
df3 <- data.frame(rbind(sku, qty, weight))
cat("\nДата-фрейм через rbind (обратите внимание на типы):\n")
print(df3)
str(df3)


# ============================================================================
# 4. ФАКТОРЫ
# ============================================================================
# Фактор — способ хранения КАТЕГОРИАЛЬНОЙ переменной.
# Внутри это целые числа плюс справочник уровней (levels).
# levels — реальные значения в данных, labels — как их показывать.

cargo_raw <- c("box", "pallet", "box", "box", "pallet", "bag", "bag", "box")

cargo <- factor(
  cargo_raw,
  levels = c("box", "pallet", "bag"),
  labels = c("Коробка", "Паллета", "Мешок")
)

cat("\n--- 4. Факторы ---\n")
print(cargo)
cat("Уровни:", paste(levels(cargo), collapse = ", "), "\n")
cat("Внутреннее представление (целые коды):\n")
print(as.integer(cargo))

# Частоты по категориям — то, ради чего фактор и нужен
cat("\nЧастотная таблица:\n")
print(table(cargo))

# Подсчёт вхождений конкретной категории.
# ВАЖНО: в методичке написано str_count(xf, ...) прямо по фактору.
# Современные версии stringr на фактор ругаются, поэтому нужен as.character().
cargo_chr <- as.character(cargo)
n_pallet <- sum(str_count(cargo_chr, pattern = "Паллета"))
cat("\nЧисло паллет (через stringr::str_count):", n_pallet, "\n")

# Штатный способ в R, без stringr — проще и надёжнее:
cat("Число паллет (через sum(cargo == ...)):", sum(cargo == "Паллета"), "\n")

# Подводный камень факторов: если значение отсутствует в levels,
# оно молча превращается в NA.
bad <- factor(c("box", "container"), levels = c("box", "pallet", "bag"))
cat("\nЗначение вне списка уровней превращается в NA:\n")
print(bad)


# ============================================================================
# 5. МНОГОМЕРНЫЕ МАССИВЫ
# ============================================================================
# Массив — обобщение матрицы на три и более измерений.
# Смысл: остатки 3 артикулов по 4 зонам на 2 складах.
# Третье измерение — это "слои" (склады).

stock_array <- array(
  1:24,
  dim = c(3, 4, 2),
  dimnames = list(
    c("SKU-100", "SKU-101", "SKU-102"),
    c("Зона A", "Зона B", "Зона C", "Зона D"),
    c("Склад Екб", "Склад Мск")
  )
)

cat("\n--- 5. Многомерный массив 3x4x2 ---\n")
print(stock_array)
cat("Размерность:", dim(stock_array), "\n")

# Обращение по трём индексам
cat("SKU-101 / Зона C / Склад Мск:", stock_array["SKU-101", "Зона C", "Склад Мск"], "\n")

# Срез — это уже матрица
cat("\nСрез по второму складу (матрица 3x4):\n")
print(stock_array[, , "Склад Мск"])

# Агрегация по выбранному измерению через apply:
# MARGIN = 3 означает "схлопнуть всё, кроме третьего измерения"
cat("\nИтого по складам:\n")
print(apply(stock_array, MARGIN = 3, FUN = sum))


# ============================================================================
# 6. СПИСКИ
# ============================================================================
# Список — самая гибкая структура: элементы могут быть любого типа
# и любой длины, включая вложенные списки и дата-фреймы.

shift_report <- list(
  date      = as.Date("2026-09-18"),
  warehouse = "Склад Екб",
  pickers   = c("Иванов", "Петров", "Сидоров"),
  metrics   = list(orders = 128, lines = 1450, errors = 3),
  orders_df = orders
)

cat("\n--- 6. Список ---\n")
str(shift_report, max.level = 2)

# Три способа доступа и разница между [ ] и [[ ]]:
cat("\nВторой комплектовщик по имени:      ", shift_report$pickers[2], "\n")
cat("Он же через [[ ]]:                   ", shift_report[["pickers"]][2], "\n")
cat("Ошибок за смену (вложенный список):  ", shift_report$metrics$errors, "\n")

# Критичное различие:
# [ ] возвращает СПИСОК из одного элемента,
# [[ ]] возвращает САМ ЭЛЕМЕНТ.
cat("\nКласс shift_report['pickers']  :", class(shift_report["pickers"]), "\n")
cat("Класс shift_report[['pickers']]:", class(shift_report[["pickers"]]), "\n")

# Обход списка функциями семейства apply
cat("\nДлина каждого элемента списка:\n")
print(sapply(shift_report, length))


# ============================================================================
# ИТОГ БЛОКА
# ============================================================================
cat("\n=== Созданные структуры ===\n")
summary_tbl <- data.frame(
  Структура = c("Вектор", "Матрица", "Дата-фрейм", "Фактор",
                "Массив", "Список"),
  Объект    = c("sku, qty, weight", "stock_matrix", "orders",
                "cargo", "stock_array", "shift_report"),
  Однородность = c("да", "да", "нет", "да (категории)", "да", "нет"),
  Размерность  = c("1", "2", "2", "1", "3", "произвольная вложенность")
)
print(summary_tbl, row.names = FALSE)
