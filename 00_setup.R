# ----------------------------------------------------------------------------
# ШАГ 0. Проверка, что мы находимся внутри RStudio-проекта
# ----------------------------------------------------------------------------
# Почему это важно: все скрипты работы используют ОТНОСИТЕЛЬНЫЕ пути
# ("data/example.txt"), а не абсолютные ("C:/Users/.../example.txt").
# Относительные пути отсчитываются от рабочей директории, а рабочая
# директория в RStudio-проекте всегда равна корню проекта.
# Это избавляет от setwd("path/to/file") из методички, который ломается
# на любом другом компьютере — в том числе на компьютере преподавателя.

cat("Текущая рабочая директория:", getwd(), "\n")
# Ожидается путь, оканчивающийся на /lr1


# ----------------------------------------------------------------------------
# ШАГ 1. Структура папок проекта
# ----------------------------------------------------------------------------
# data/   — исходные файлы, которые нам выдали (только чтение)
# output/ — всё, что скрипты создают сами (xlsx, графики, txt)
# Разделение входа и выхода — требование воспроизводимости:
# папку output можно удалить целиком и пересобрать запуском скриптов.

dir.create("data",   showWarnings = FALSE)
dir.create("output", showWarnings = FALSE)

cat("Папки созданы. Содержимое проекта:\n")
print(list.files())


