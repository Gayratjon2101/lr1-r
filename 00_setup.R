# ----------------------------------------------------------------------------
# ШАГ 5. Проверка, что исходные файлы на месте
# ----------------------------------------------------------------------------
# Файлы из архива нужно положить в папку data/ и ПЕРЕИМЕНОВАТЬ
# 1тек.txt -> 1.txt, ..., 5тек.txt -> 5.txt
# (методичка ссылается на них как на 1.txt ... 5.txt; кириллица
#  в именах файлов на Windows регулярно даёт проблемы с кодировкой)

required_files <- c("example.txt", "matrix.txt", "example_csv.csv",
                    "1.txt", "2.txt", "3.txt", "4.txt", "5.txt")

check <- file.exists(file.path("data", required_files))
names(check) <- required_files

cat("\nНаличие исходных файлов в папке data/:\n")
print(check)

if (all(check)) {
  cat("\nВсе файлы на месте. Можно переходить к 01_io.R\n")
} else {
  cat("\nОТСУТСТВУЮТ:", paste(required_files[!check], collapse = ", "), "\n")
}
