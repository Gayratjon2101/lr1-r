# ============================================================================
# ЧАСТЬ А. Очистка набора данных ВОЗ
# ============================================================================
# tidyr::who — статистика заболеваемости туберкулёзом по странам и годам.
# Набор «неаккуратный»: в ОДНОМ имени столбца закодированы СРАЗУ ЧЕТЫРЕ
# признака. Например, new_sp_m014 означает:
#   new  — новые случаи (в этом наборе все случаи новые)
#   sp   — тип заболевания
#   m    — пол (m — мужской, f — женский)
#   014  — возрастная группа 0–14 лет
#
# Аккуратный (tidy) вид: каждый признак — отдельный столбец,
# каждое наблюдение — отдельная строка.

who <- tidyr::who

cat("--- А.0. Исходный набор ---\n")
cat("Размер:", dim(who), "(строк, столбцов)\n")
cat("Первые 8 имён столбцов:\n")
print(head(names(who), 8))


# ----------------------------------------------------------------------------
# А.1. Собираем 56 столбцов с кодами в два: key (код) и cases (число случаев)
# ----------------------------------------------------------------------------
# na.rm = TRUE отбрасывает пустые значения — их в наборе большинство.

who1 <- who %>%
  gather(new_sp_m014:newrel_f65, key = "key", value = "cases", na.rm = TRUE)

cat("\n--- А.1. После gather ---\n")
cat("Размер:", dim(who1), "\n")

# gather() в tidyr устарела (superseded). Современная замена — pivot_longer().
# Показываем, что результат тот же:
who1_modern <- who %>%
  pivot_longer(new_sp_m014:newrel_f65, names_to = "key",
               values_to = "cases", values_drop_na = TRUE)

cat("pivot_longer даёт столько же строк:",
    nrow(who1_modern) == nrow(who1), "\n")


# ----------------------------------------------------------------------------
# А.2. Изучаем коды
# ----------------------------------------------------------------------------
cat("\n--- А.2. Частота кодов (первые 10) ---\n")
print(head(who1 %>% count(key), 10))

# РАСШИФРОВКА КОДОВ — исправленная.
# В методичке здесь опечатки, которые искажают смысл:
#   «ul» вместо old, «reel» вместо rel, «up» вместо ep,
#   «sun» и «spa» вместо sn и sp,
#   «оставшиеся цифры дают пол» — на самом деле цифры дают ВОЗРАСТ.
# Правильно:
#   rel — рецидив
#   ep  — внелёгочный туберкулёз
#   sn  — лёгочный, мазок отрицательный (не выявляется мазком)
#   sp  — лёгочный, мазок положительный (выявляется мазком)
#   буква после второго подчёркивания — пол, цифры после неё — возраст


# ----------------------------------------------------------------------------
# А.3. Исправляем непоследовательность в именах
# ----------------------------------------------------------------------------
# У всех кодов вид new_sp_m014, но у рецидивов — newrel_m014,
# без подчёркивания. Из-за этого разбивка по «_» дала бы сбой.
# Приводим к единому виду: newrel -> new_rel

who2 <- who1 %>%
  mutate(key = str_replace(key, "newrel", "new_rel"))

cat("\n--- А.3. Проверка: кодов без нужного числа подчёркиваний ---\n")
cat("До исправления:  ", sum(str_count(who1$key, "_") != 2), "\n")
cat("После исправления:", sum(str_count(who2$key, "_") != 2), "\n")


# ----------------------------------------------------------------------------
# А.4. Разбиваем код на части
# ----------------------------------------------------------------------------
who3 <- who2 %>%
  separate(key, c("new", "type", "sexage"), sep = "_")

cat("\n--- А.4. Значения столбца new ---\n")
print(who3 %>% count(new))
# Значение одно — "new". Столбец не несёт информации, его можно убрать.
# Это же доказывает, что «старых случаев» в наборе нет вовсе.

# iso2 и iso3 — коды страны, дублирующие столбец country
who4 <- who3 %>%
  select(-new, -iso2, -iso3)

# sep = 1 — ЧИСЛО: разрезать после первого СИМВОЛА.
# m014 -> "m" и "014";  f65 -> "f" и "65"
who5 <- who4 %>%
  separate(sexage, c("sex", "age"), sep = 1)

cat("\n--- А.5. Аккуратный набор ---\n")
print(head(who5, 8))
cat("Значения пола:", paste(sort(unique(who5$sex)), collapse = ", "), "\n")
cat("Значения возраста:", paste(sort(unique(who5$age)), collapse = ", "), "\n")


# ----------------------------------------------------------------------------
# А.6. Ошибки в «коротком» варианте из методички
# ----------------------------------------------------------------------------
# Методичка предлагает «то же самое, только короче», но результат НЕ тот же.
# Ошибка 1: диапазон new_sp_f014:newrel_f65 начинается с женских столбцов
#           и теряет 7 мужских столбцов new_sp_m014 ... new_sp_m65.
# Ошибка 2: sep = "1" — это СТРОКА, то есть разрезать по символу «1»,
#           а не после первого символа. m014 -> "m0" и "4", а m65,
#           где единицы нет вовсе, не разрезается.
# Воспроизводим вариант методички как есть и сравниваем:

who_short <- suppressWarnings(
  who %>%
    gather(code, value, new_sp_f014:newrel_f65, na.rm = TRUE) %>%
    mutate(code = str_replace(code, "newrel", "new_rel")) %>%
    separate(code, c("new", "var", "sexage")) %>%
    select(-new, -iso2, -iso3) %>%
    separate(sexage, c("sex", "age"), sep = "1")
)

cat("\n--- А.6. Сравнение с коротким вариантом методички ---\n")
cat("Строк в правильном варианте:     ", nrow(who5), "\n")
cat("Строк в коротком варианте:       ", nrow(who_short), "\n")
cat("Значения пола в коротком варианте:",
    paste(sort(unique(who_short$sex)), collapse = ", "), "\n")
cat("Пустых значений возраста:        ", sum(is.na(who_short$age)), "\n")


# ----------------------------------------------------------------------------
# А.7. Доводим до читаемого вида и проверяем результат
# ----------------------------------------------------------------------------
# Возраст "014" -> "0-14", "1524" -> "15-24", "65" -> "65+".
# Регулярное выражение: ^(\d{1,2})(\d{2})$ — одна-две цифры, затем ровно две.
#   ^ и $ — начало и конец строки; ( ) — группы; \1 и \2 — ссылки на них.

type_labels <- c(
  sp  = "лёгочный, мазок +",
  sn  = "лёгочный, мазок -",
  ep  = "внелёгочный",
  rel = "рецидив"
)

who_tidy <- who5 %>%
  mutate(
    age = ifelse(age == "65", "65+",
                 str_replace(age, "^(\\d{1,2})(\\d{2})$", "\\1-\\2")),
    type_label = unname(type_labels[type]),
    sex = ifelse(sex == "m", "муж", "жен")
  )

cat("\n--- А.7. Возрастные группы после преобразования ---\n")
print(sort(unique(who_tidy$age)))

summary_by_type <- who_tidy %>%
  group_by(type_label, sex) %>%
  summarise(cases = sum(cases), .groups = "drop") %>%
