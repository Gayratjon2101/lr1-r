# ============================================================================
# ЧАСТЬ Б. Основы регулярных выражений
# ============================================================================
# Регулярное выражение (regex) — шаблон для поиска в тексте.
# Вместо «найди строку A-01-02» можно сказать
# «найди букву, дефис, две цифры, дефис, две цифры».

x <- c("apple", "banana", "pear")

cat("\n--- Б.1. Функции из методички на её примере ---\n")
cat("str_detect(x, 'e')  :", str_detect(x, "e"), "\n")   # есть ли совпадение
cat("str_count(x, 'a')   :", str_count(x, "a"), "\n")    # сколько совпадений
cat("str_subset(x, 'an') :", str_subset(x, "an"), "\n")  # только подходящие
cat("str_replace(x,'a','A'):", str_replace(x, "a", "A"), "\n")  # первое
cat("str_replace_all     :", str_replace_all(x, "a", "A"), "\n") # все

cat("\nstr_view выделяет совпадения в угловых скобках:\n")
print(str_view(x, "an"))

# Б.2. Пример на своих данных: адреса складских ячеек
# Формат адреса: зона (буква) - ряд (2 цифры) - ярус (2 цифры)
cells <- c("A-01-02", "B-12-01", "C-3-04", "D-05-10", "склад", "AA-01-01")

valid_cell <- "^[A-Z]-\\d{2}-\\d{2}$"
#  ^        начало строки
#  [A-Z]    ровно одна заглавная латинская буква
#  -        дефис
#  \d{2}    ровно две цифры
#  $        конец строки — без него "AA-01-01" прошёл бы частично

cat("\n--- Б.2. Проверка формата адресов ячеек ---\n")
print(data.frame(cell = cells, valid = str_detect(cells, valid_cell)))

# Разбор адреса на части через группы
parts <- str_match(cells, "^([A-Z])-(\\d{2})-(\\d{2})$")
cat("\nРазбор корректных адресов на зону, ряд и ярус:\n")
print(parts[!is.na(parts[, 1]), , drop = FALSE])


# ============================================================================
# ЧАСТЬ В. ЗАДАНИЕ 5 — найти номер телефона в тексте
# ============================================================================

find_phone <- c("Это пример текстовой строки внутри которой может находиться 790012345-67 мобильный либо городской 73432220000")

# ----------------------------------------------------------------------------
# В.1. Что считаем телефоном
# ----------------------------------------------------------------------------
# Российский номер: первая цифра 7 или 8, затем ровно 10 цифр.
# Между цифрами могут стоять пробелы, дефисы, скобки.
# 790012345-67  -> 7 900 123 45-67  (11 цифр, есть дефис)
# 73432220000   -> 7 343 222 00 00  (11 цифр подряд)

# ----------------------------------------------------------------------------
# В.2. Наивный шаблон и его проблема
# ----------------------------------------------------------------------------
naive <- "\\d[\\d-]{9,}\\d"
# цифра, затем 9 и более цифр или дефисов, затем цифра

cat("\n--- В.2. Наивный шаблон на тексте задания ---\n")
print(str_extract_all(find_phone, naive)[[1]])
# На тексте задания работает. Но проверим на других строках.

# ----------------------------------------------------------------------------
# В.3. Строгий шаблон
# ----------------------------------------------------------------------------
phone_regex <- "(?<!\\d)[78](?:[\\s()\\-]*\\d){10}(?!\\d)"
#  (?<!\d)        перед номером НЕ должно быть цифры (не кусок длинного числа)
#  [78]           первая цифра — 7 или 8
#  (?: ... ){10}  ровно 10 раз повторить:
#     [\s()\-]*   любое число пробелов, скобок, дефисов (в т.ч. ни одного)
#     \d          и одна цифра
#  (?!\d)         после номера НЕ должно быть цифры

cat("\n--- В.3. Строгий шаблон на тексте задания ---\n")
phones <- str_extract_all(find_phone, phone_regex)[[1]]
print(phones)
print(str_view(find_phone, phone_regex))

# ----------------------------------------------------------------------------
# В.4. Проверка на трудных случаях
# ----------------------------------------------------------------------------
# Тест хорош, только если в нём есть строки, где шаблон должен ОТКАЗАТЬ.
tests <- data.frame(
  text = c(
    "+7 (912) 345-67-89",            # телефон со скобками
    "8 343 222-00-00",               # телефон через 8, с пробелами
    "ИНН 7701234567",                # 10 цифр с 7 — НЕ телефон
    "заказ 79991234567890",          # 14 цифр — НЕ телефон
    "дата 2026-10-04"                # дата с дефисами — НЕ телефон
  ),
  expected = c(TRUE, TRUE, FALSE, FALSE, FALSE)
)

tests$naive  <- str_detect(tests$text, naive)
tests$strict <- str_detect(tests$text, phone_regex)

cat("\n--- В.4. Сравнение шаблонов (expected — правильный ответ) ---\n")
print(tests)
cat("Наивный шаблон, ошибок: ", sum(tests$naive  != tests$expected), "\n")
cat("Строгий шаблон, ошибок: ", sum(tests$strict != tests$expected), "\n")

# ----------------------------------------------------------------------------
# В.5. Нормализация найденных номеров
# ----------------------------------------------------------------------------
# Номера записаны по-разному. Приводим к единому виду:
#  1) убираем всё, кроме цифр:      \D — любой НЕ-цифровой символ
#  2) ведущую 8 меняем на 7
#  3) раскладываем по группам в формат +7 (XXX) XXX-XX-XX
#  4) определяем тип: мобильные коды в России начинаются с 9

normalize_phone <- function(p) {
  digits <- str_remove_all(p, "\\D")
  digits <- str_replace(digits, "^8", "7")
  str_replace(digits, "^7(\\d{3})(\\d{3})(\\d{2})(\\d{2})$",
              "+7 (\\1) \\2-\\3-\\4")
}

result <- data.frame(
  found      = phones,
  normalized = normalize_phone(phones),
  code       = str_sub(str_remove_all(phones, "\\D"), 2, 4)
)
result$type <- ifelse(str_detect(result$code, "^9"), "мобильный", "городской")

cat("\n--- В.5. Итог задания 5 ---\n")
print(result)
# Код 343 — телефонный код Екатеринбурга.

write.xlsx(
  list(phones = result, regex_tests = tests, who_summary = summary_by_type),
  file = "output/phones_found.xlsx",
  overwrite = TRUE
)
